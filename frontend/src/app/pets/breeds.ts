// คำแนะนำสำหรับประเภทที่เลือก (ไม่รู้ประเภท = แสดงทั้งหมด)
export function breedSuggestions(typeName?: string | null): string[] {
  const list = (typeName && BREEDS_BY_TYPE[typeName]) || ALL_BREEDS;
  return [...list, ...BREED_COMMON];
}
