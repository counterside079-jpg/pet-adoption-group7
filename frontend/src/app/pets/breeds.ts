// ใช้ได้กับทุกประเภท
export const BREED_COMMON = ['พันธุ์ผสม', 'ไม่ทราบสายพันธุ์'];

// รวมทุกสายพันธุ์ (ไม่รวม "พันธุ์ผสม" ฯลฯ เพราะไม่เหมาะเป็นปุ่มลองค้น)
